create schema if not exists qualidade;

-- Métricas: 1 linha = 1 regra x 1 tabela x 1 execução
create table if not exists qualidade.metricas_qualidade (
  id_metrica          integer generated by default as identity primary key,
  regra               varchar(80)  not null,
  dimensao            varchar(30)  not null check (dimensao in (
                        'completude','unicidade','validade','consistencia',
                        'acuracia','integridade_referencial','atualidade')),
  tabela              varchar(60)  not null,
  registros_avaliados integer      not null,
  registros_falha     integer      not null,
  percentual_falha    numeric(6,2) not null,
  data_execucao       timestamp    not null default now()
);

-- Catálogo de decisões (regra -> decisão e justificativa)
create table if not exists qualidade.decisoes (
  regra         varchar(80) primary key,
  decisao       varchar(40) not null,
  justificativa text        not null
);

-- Profiling: 1 linha = 1 coluna x 1 tabela x 1 execução
create table if not exists qualidade.profiling (
  tabela varchar(60), coluna varchar(60), tipo varchar(30),
  total integer, nulos integer, vazios integer, pct_nulos numeric(6,2), distintos integer,
  minimo text, maximo text, distribuicao text,
  data_execucao timestamp not null default now()
);

-- Antes x depois dos indicadores de negócio
create table if not exists qualidade.antes_depois (
  indicador     varchar(60) not null,
  recorte       varchar(60) not null,
  valor_antes   numeric(18,3),
  valor_depois  numeric(18,3),
  diferenca     numeric(18,3),
  diferenca_pct numeric(8,2),
  data_execucao timestamp not null default now()
);

-- Cadastro de usinas
create table if not exists qualidade.usina_limpa (like campo_real_energia.usina);
alter table qualidade.usina_limpa
  add column if not exists correcao text,
  add column if not exists flag_inicio_operacao_invalido boolean default false;

create table if not exists qualidade.usina_quarentena (like campo_real_energia.usina);
alter table qualidade.usina_quarentena
  add column if not exists motivo text,
  add column if not exists id_usina_canonico integer;

-- Paradas
create table if not exists qualidade.parada_usina_limpa (like campo_real_energia.parada_usina);
create table if not exists qualidade.parada_usina_quarentena (like campo_real_energia.parada_usina);
alter table qualidade.parada_usina_quarentena add column if not exists motivo text;

-- Medição
create table if not exists qualidade.medicao_geracao_limpa (like campo_real_energia.medicao_geracao);
alter table qualidade.medicao_geracao_limpa
  add column if not exists energia_mwh_original numeric(12,3),
  add column if not exists correcao             varchar(40),
  add column if not exists flag_outlier         boolean default false,
  add column if not exists flag_atraso          boolean default false,
  add column if not exists flag_recebido_antes  boolean default false;

create table if not exists qualidade.medicao_geracao_quarentena (like campo_real_energia.medicao_geracao);
alter table qualidade.medicao_geracao_quarentena
  add column if not exists energia_mwh_original numeric(12,3),
  add column if not exists motivo text;

