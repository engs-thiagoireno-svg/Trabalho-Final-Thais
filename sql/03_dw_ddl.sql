create schema if not exists dw_campo_real;

create table if not exists dw_campo_real.dim_tempo (
    sk_tempo         integer generated by default as identity primary key,
    data_hora        timestamp   not null unique,
    data             date        not null,
    hora             smallint    not null,
    dia              smallint    not null,
    mes              smallint    not null,
    nome_mes         varchar(20) not null,
    ano_mes          char(7)     not null,
    trimestre        smallint    not null,
    nome_trimestre   varchar(10) not null,
    ano              smallint    not null,
    dia_semana       smallint    not null,
    nome_dia_semana  varchar(20) not null,
    fim_de_semana    boolean     not null,
    feriado          boolean     not null default false,
    nome_feriado     varchar(60),
    tipo_feriado     varchar(25),
    dia_util         boolean     not null,
    estacao_ano      varchar(15) not null,
    patamar_carga    varchar(15) not null
);

create table if not exists dw_campo_real.dim_submercado (
    sk_submercado  integer generated by default as identity primary key,
    cod_submercado varchar(2)  not null unique,
    nome           varchar(40) not null,
    regioes        varchar(80) not null
);

create table if not exists dw_campo_real.dim_fonte (
    sk_fonte        integer generated by default as identity primary key,
    id_fonte_origem smallint,
    cod_fonte       varchar(10) not null unique,
    descricao       varchar(40) not null,
    renovavel       boolean     not null,
    intermitente    boolean     not null
);

create table if not exists dw_campo_real.dim_usina (
    sk_usina             integer generated by default as identity primary key,
    id_usina_origem      integer,
    cod_usina            varchar(12)  not null,
    nome                 varchar(80)  not null,
    sk_fonte             integer      not null default -1 references dw_campo_real.dim_fonte(sk_fonte),
    cod_fonte            varchar(10)  not null,
    fonte                varchar(40)  not null,
    renovavel            boolean      not null default false,
    intermitente         boolean      not null default false,
    sk_submercado        integer      not null default -1 references dw_campo_real.dim_submercado(sk_submercado),
    cod_submercado       varchar(2)   not null,
    submercado           varchar(40)  not null,
    uf                   varchar(2)   not null,
    municipio            varchar(60)  not null,
    latitude             numeric(9,6),
    longitude            numeric(9,6),
    potencia_mw          numeric(8,2) not null,
    data_inicio_operacao date,
    situacao             varchar(20)  not null,
    vigencia_inicio      date         not null,
    vigencia_fim         date,
    registro_atual       boolean      not null default true
);

create index if not exists ix_dim_usina_cod_atual
    on dw_campo_real.dim_usina (cod_usina, registro_atual);

create table if not exists dw_campo_real.dim_tipo_parada (
    sk_tipo_parada integer generated by default as identity primary key,
    tipo           varchar(20)  not null,
    motivo         varchar(120) not null,
    unique (tipo, motivo)
);

