-- Grão: 1 linha = 1 usina em 1 hora
create table if not exists dw_campo_real.fato_geracao (
    sk_tempo           integer       not null references dw_campo_real.dim_tempo(sk_tempo),
    sk_usina           integer       not null references dw_campo_real.dim_usina(sk_usina),
    sk_fonte           integer       not null default -1 references dw_campo_real.dim_fonte(sk_fonte),
    sk_submercado      integer       not null default -1 references dw_campo_real.dim_submercado(sk_submercado),
    energia_mwh        numeric(12,3) not null,
    disponibilidade_mw numeric(8,2)  not null,
    pld_rs_mwh         numeric(10,2),
    receita_rs         numeric(14,2),
    flag_outlier       boolean       not null default false,
    flag_atraso        boolean       not null default false,
    primary key (sk_tempo, sk_usina)
);

create index if not exists ix_fato_geracao_usina on dw_campo_real.fato_geracao (sk_usina);
create index if not exists ix_fato_geracao_submercado_tempo on dw_campo_real.fato_geracao (sk_submercado, sk_tempo);

-- Grão: 1 linha = 1 submercado em 1 hora
create table if not exists dw_campo_real.fato_preco (
    sk_tempo      integer       not null references dw_campo_real.dim_tempo(sk_tempo),
    sk_submercado integer       not null references dw_campo_real.dim_submercado(sk_submercado),
    pld_rs_mwh    numeric(10,2) not null,
    primary key (sk_tempo, sk_submercado)
);

create index if not exists ix_fato_preco_submercado on dw_campo_real.fato_preco (sk_submercado);

-- Grão: 1 linha = 1 usina (ponto de clima) em 1 hora
create table if not exists dw_campo_real.fato_clima (
    sk_tempo      integer      not null references dw_campo_real.dim_tempo(sk_tempo),
    sk_usina      integer      not null references dw_campo_real.dim_usina(sk_usina),
    sk_fonte      integer      not null default -1 references dw_campo_real.dim_fonte(sk_fonte),
    sk_submercado integer      not null default -1 references dw_campo_real.dim_submercado(sk_submercado),
    temperatura_c numeric(5,2),
    radiacao_wm2  numeric(7,2),
    vento_10m_ms  numeric(5,2),
    vento_100m_ms numeric(5,2),
    vento_ms      numeric(5,2),
    chuva_mm      numeric(6,2),
    primary key (sk_tempo, sk_usina)
);

create index if not exists ix_fato_clima_usina on dw_campo_real.fato_clima (sk_usina);

-- Grão: 1 linha = 1 parada de 1 usina
create table if not exists dw_campo_real.fato_parada (
    sk_parada              integer generated by default as identity primary key,
    id_parada_origem       integer       not null unique,
    sk_tempo_inicio        integer       not null references dw_campo_real.dim_tempo(sk_tempo),
    sk_tempo_fim           integer       not null references dw_campo_real.dim_tempo(sk_tempo),
    sk_usina               integer       not null references dw_campo_real.dim_usina(sk_usina),
    sk_fonte               integer       not null default -1 references dw_campo_real.dim_fonte(sk_fonte),
    sk_submercado          integer       not null default -1 references dw_campo_real.dim_submercado(sk_submercado),
    sk_tipo_parada         integer       not null references dw_campo_real.dim_tipo_parada(sk_tipo_parada),
    horas_parada           numeric(8,2)  not null,
    energia_nao_gerada_mwh numeric(12,3) not null,
    receita_nao_gerada_rs  numeric(14,2)
);

create or replace view dw_campo_real.vw_geracao_analitica as
select
    fg.sk_tempo,
    t.data_hora,
    t.data,
    t.hora,
    t.ano,
    t.mes,
    t.nome_mes,
    t.ano_mes,
    t.trimestre,
    t.nome_trimestre,
    t.dia_semana,
    t.nome_dia_semana,
    t.fim_de_semana,
    t.feriado,
    t.nome_feriado,
    t.dia_util,
    t.estacao_ano,
    t.patamar_carga,
    fg.sk_usina,
    u.cod_usina,
    u.nome as nome_usina,
    u.uf,
    u.municipio,
    u.potencia_mw,
    u.situacao,
    fg.sk_fonte,
    f.cod_fonte,
    f.descricao as nome_fonte,
    f.renovavel,
    f.intermitente,
    fg.sk_submercado,
    s.cod_submercado,
    s.nome as nome_submercado,
    s.regioes as regioes_submercado,
    fg.energia_mwh,
    fg.disponibilidade_mw,
    coalesce(fg.pld_rs_mwh, fp.pld_rs_mwh) as pld_rs_mwh,
    coalesce(fg.receita_rs, round(fg.energia_mwh * fp.pld_rs_mwh, 2)) as receita_rs,
    fc.temperatura_c,
    fc.radiacao_wm2,
    fc.vento_10m_ms,
    fc.vento_100m_ms,
    fc.vento_ms,
    fc.chuva_mm,
    fg.flag_outlier,
    fg.flag_atraso
from dw_campo_real.fato_geracao fg
join dw_campo_real.dim_tempo t on t.sk_tempo = fg.sk_tempo
join dw_campo_real.dim_usina u on u.sk_usina = fg.sk_usina
join dw_campo_real.dim_fonte f on f.sk_fonte = fg.sk_fonte
join dw_campo_real.dim_submercado s on s.sk_submercado = fg.sk_submercado
left join dw_campo_real.fato_preco fp
    on fp.sk_tempo = fg.sk_tempo and fp.sk_submercado = fg.sk_submercado
left join dw_campo_real.fato_clima fc
    on fc.sk_tempo = fg.sk_tempo and fc.sk_usina = fg.sk_usina;

create or replace view dw_campo_real.vw_qualidade_metricas as
with ultima as (
    select max(data_execucao) as max_dt
    from qualidade.metricas_qualidade
)
select
    m.id_metrica,
    m.regra,
    m.dimensao,
    m.tabela,
    case
        when m.tabela like 'qualidade.%' then 'Depois da limpeza (qualidade)'
        when m.tabela like 'extracao.%' then 'Fonte externa (extracao)'
        else 'Antes da limpeza (origem)'
    end as camada,
    m.registros_avaliados,
    m.registros_falha,
    m.percentual_falha,
    round(100.00 - least(m.percentual_falha, 100.00), 2) as indice_qualidade_pct,
    d.decisao,
    d.justificativa,
    m.data_execucao
from qualidade.metricas_qualidade m
join ultima u on m.data_execucao = u.max_dt
left join qualidade.decisoes d on d.regra = m.regra;

create or replace view dw_campo_real.vw_qualidade_antes_depois as
with ultima as (
    select max(data_execucao) as max_dt
    from qualidade.antes_depois
)
select
    a.indicador,
    a.recorte,
    a.valor_antes,
    a.valor_depois,
    a.diferenca,
    a.diferenca_pct,
    a.data_execucao
from qualidade.antes_depois a
join ultima u on a.data_execucao = u.max_dt;
