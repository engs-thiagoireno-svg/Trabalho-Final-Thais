create schema if not exists extracao;

create table if not exists extracao.raw_pld (
    id_raw        bigint generated by default as identity primary key,
    origem        text      not null,
    resource_id   text      not null,
    pagina_offset integer   not null,
    extraido_em   timestamp not null default now(),
    payload       jsonb     not null
);

create table if not exists extracao.pld_horario (
    data_hora      timestamp     not null,
    cod_submercado char(2)       not null,
    pld_rs_mwh     numeric(10,2) not null,
    id_raw         bigint,
    primary key (data_hora, cod_submercado)
);

create table if not exists extracao.raw_clima (
    id_raw      bigint generated by default as identity primary key,
    cod_usina   varchar(12) not null,
    origem      text        not null,
    extraido_em timestamp   not null default now(),
    payload     jsonb       not null
);

create table if not exists extracao.clima_horario (
    cod_usina     varchar(12) not null,
    data_hora     timestamp   not null,
    temperatura_c numeric(5,2),
    radiacao_wm2  numeric(7,2),
    vento_10m_ms  numeric(5,2),
    vento_100m_ms numeric(5,2),
    chuva_mm      numeric(6,2),
    id_raw        bigint,
    primary key (cod_usina, data_hora)
);

create table if not exists extracao.log_extracao (
    id_log          integer generated by default as identity primary key,
    processo        varchar(40) not null,
    fonte           varchar(60) not null,
    inicio          timestamp   not null,
    fim             timestamp,
    linhas_lidas    integer,
    linhas_gravadas integer,
    status          varchar(20) not null,
    erro            text
);